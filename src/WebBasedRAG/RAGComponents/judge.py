class JudgeDecision(str, Enum):
    PASS = "PASS"
    REWRITE = "REWRITE"
    SEARCH_AGAIN = "SEARCH_AGAIN"
    AMBIGUOUS = "AMBIGUOUS"


class JudgeEvaluation(BaseModel):
    decision: JudgeDecision = Field(
        description="PASS: The answer is PERFECT and satisfies the user input. "
                    "REWRITE: The context section contains the answer but the model didn't capture it correctly or violated tone rules. "
                    "SEARCH_AGAIN: The context is INSUFFICIENT for the answer or temporally outdated, so a new search must be done."
    )
    reasoning: str = Field(
        description="Explain the reason of the evaluation. If you choose SEARCH_AGAIN suggest what the agent must search for to meet the goal."
    )

class AnswerJudge:
    def __init__(self, llm: BaseChatModel):
        self.llm = llm
        
        # 1. Usiamo il BINDING NATIVO: Questo impone il JSON Schema a livello di motore Ollama.
        # Il modello non potrà fisicamente generare testo discorsivo.
        self.structured_llm = self.llm.with_structured_output(JudgeEvaluation)
        
        # 2. Rimuoviamo {format_instructions}, non servono più!
        self.prompt = ChatPromptTemplate.from_messages([
            ("system", """You are an expert impartial judge in an Agentic RAG system for the DIEM department of UNISA. 

Do NOT use your internal training date. We are currently in this datetime (CURRENT SYSTEM DATETIME): {current_datetime}

Your task is to evaluate the Context retrieved by an agent and the Answer generated by an assistant.

EVALUATION STEPS (Think step-by-step in your reasoning):
1. CONTEXT CHECK: Does the 'AVAILABLE CONTEXT' contain sufficient information to answer the 'ORIGINAL QUESTION'?
2. TEMPORAL RELEVANCE CHECK: Look strictly at the 'CURRENT SYSTEM DATETIME'. Assume the user requires the most current facts. Evaluate the "information decay": in a university setting, topics like curricula, exams, deadlines, and regulations update annually. If a document is multiple years old relative to the current date (e.g., a 2021 document evaluated in 2026), it has a high probability of decay and is inherently unreliable for present-day queries. You MUST mark it as INVALID and trigger SEARCH_AGAIN, instructing the search agent to append the current academic year to its next query.
3. AMBIGUITY CHECK: Evaluate if the 'ORIGINAL QUESTION' is generic or incomplete. If the 'AVAILABLE CONTEXT' reveals multiple distinct and valid entities/options that equally match the query, recognize that providing a single definitive answer is impossible or incorrect. In this scenario, the system must not guess, but must ask the user to clarify by presenting the available alternatives.
4. ANSWER CHECK: Is the 'ANSWER TO EVALUATE' entirely faithful to the Context, without hallucinating extra data?
5. TONE & PERSONA CHECK: Does the answer reflect the persona of a direct, helpful, and professional agent representing the DIEM department? 
6. DATE TRANSPARENCY CHECK: If the 'AVAILABLE CONTEXT' contains a publication or reference date, and the user did NOT specify a precise timeframe, does the 'ANSWER TO EVALUATE' explicitly mention this date to avoid misleading the user?

CRITICAL TONE RULES: 
The assistant MUST NOT "break character". It must NEVER expose its internal mechanics. 
Flags for a BAD tone include:
- Being overly apologetic or robotic (e.g., "As an AI...", "I don't have enough context...").
- Refusing to answer when the data is actually right there in the context.

DECISION RULES:
- PASS: Trigger this if ALL standard conditions are met (Context has the answer, Answer is faithful, tone is natural, dates are transparent). 
  OR trigger this if the query is broad, the Context contains multiple valid alternatives, and the Answer naturally asks the user to clarify/narrow down their choice based on those specific alternatives without breaking character.
- REWRITE: Trigger this decision if ANY of the following occur:
  a) The Context is valid and contains the answer, BUT the Answer includes invented data.
  b) The Answer violates the CRITICAL TONE RULES.
  c) The Context contains dated information (but is still acceptable), and the Answer fails to explicitly declare this date to the user.
  d) The Context contains multiple valid alternatives for a broad query, but the Answer fails to ask the user to clarify, or asks for clarification in a generic/robotic way without using the available options.
  e) The Context is valid but the answer is not complete, and does not contain all the data mentioned.
- SEARCH_AGAIN: Trigger this if the Context DOES NOT contain the answer AND does not contain any useful alternatives to clarify the user's intent. Also trigger this if it fails the TEMPORAL RELEVANCE CHECK. In your reasoning, suggest specific concepts the search agent should use.  CRITICAL: If the context is missing the final answer BUT contains distinct options to clarify a broad query, DO NOT trigger SEARCH_AGAIN. You MUST trigger AMBIGUOUS.
- AMBIGUOUS: Trigger this decision ONLY IF the 'ORIGINAL QUESTION' is broad/generic AND the 'AVAILABLE CONTEXT' explicitly provides multiple distinct valid categories/options to narrow down the query. This has ABSOLUTE PRIORITY over SEARCH_AGAIN. Do not instruct the system to blindly search for all possibilities. Instead, stop the execution and ask the user to clarify using the found options. In your 'reasoning', you MUST explicitly list the distinct options found.

LENIENCY DIRECTIVE (CRITICAL - FOLLOW THIS STRICTLY):
{leniency_rules}

CRITICAL OUTPUT RULE:
Reply ONLY with a valid JSON object. Do NOT include any preamble, conversational text, or markdown code blocks (like ```json). All your reasoning must go inside the "reasoning" JSON field."""),
            ("human", "ORIGINAL QUESTION: {query}\n\nAVAILABLE CONTEXT:\n{context}\n\nANSWER TO EVALUATE:\n{answer}")
        ])
        
        # 3. La chain ora usa direttamente il LLM strutturato
        self.chain = self.prompt | self.structured_llm

    def evaluate(self, query: str, context: str, answer: str, current_iter: int = 1, max_iter: int = 3, global_iter: int = 1, max_global_iter: int = 3) -> JudgeEvaluation:
        # Calcoliamo la data esatta in questo preciso istante
        current_dt = datetime.now().strftime("%A, %Y-%m-%d %H:%M:%S")
        
        # --- LOGICA DI RILASSAMENTO TEMPORALE (Sui tentativi di ricerca globale) ---
        if global_iter >= max_global_iter:
            temporal_leniency = "CRITICAL TEMPORAL OVERRIDE: We are at the final search attempt. You MUST IGNORE the 'TEMPORAL RELEVANCE CHECK'. Accept older information (e.g., from past years) if nothing newer is present. DO NOT output SEARCH_AGAIN for outdated info, just ensure the answer explicitly states the year."
        elif global_iter > 1:
            temporal_leniency = "We have already tried searching once. You can be more forgiving with dates. Accept slightly older data if recent data isn't available."
        else:
            temporal_leniency = "STRICT TEMPORAL MODE: Enforce the 'TEMPORAL RELEVANCE CHECK' perfectly. If data is heavily outdated, trigger SEARCH_AGAIN."

        # --- LOGICA DI RILASSAMENTO RISPOSTA (Sui tentativi di riscrittura) ---
        if current_iter == 1:
            leniency_rules = f"STRICT MODE: You must enforce all tone and completeness rules perfectly. {temporal_leniency}"
        elif current_iter < max_iter:
            leniency_rules = f"RELAXED MODE: Be more forgiving. Ignore minor tone violations. {temporal_leniency}"
        else:
            leniency_rules = f"CRITICAL FINAL REWRITE ATTEMPT ({current_iter}/{max_iter}): You MUST be extremely lenient. Accept partial or imperfect answers. PASS anything that is not a pure hallucination. Ignore tone and style completely. {temporal_leniency}"

        print(f"   ⚖️ [GIUDICE] Valutazione in corso... (Global Iter: {global_iter}/{max_global_iter} | Rewrite Iter: {current_iter}/{max_iter})")
        
        callbacks = [langfuse_handler] if os.getenv("IS_LANGFUSE_ENABLED") else []
        
        try:
            return self.chain.invoke({
                "current_datetime": current_dt,
                "leniency_rules": leniency_rules, 
                "query": query, 
                "context": context, 
                "answer": answer
            }, config={"callbacks": callbacks})
            
        except Exception as e:

            # SE IL PARSER FALLISCE, NON CRASHIAMO, MA FACCIAMO UN FALLBACK!
            testo_grezzo = getattr(e, 'llm_output', str(e))
            print(f"\n   ⚠️ [GIUDICE WARN] Il modello non ha generato JSON valido.")
            print(f"      Risposta catturata: {testo_grezzo[:150]}...")
            
            # Restituiamo una valutazione di "Emergenza" che forza l'agente a riprovare
            return JudgeEvaluation(
                decision=JudgeDecision.SEARCH_AGAIN,
                reasoning="The evaluator failed to format the response as JSON. Please try to extract the context again or formulate a better search."
            )